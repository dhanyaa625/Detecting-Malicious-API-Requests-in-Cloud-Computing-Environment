# 1. GRAPH DATA LOADING (From Member 3's Output)
# ─────────────────────────────────────────────────────────────────────────────

class MalwareGraphDataset(Dataset):
    """
    Dataset class for loading graph data from Member 3's data_to_graph.py output
    
    Expected structure:
    - GRAPH_DATA_DIR/graph_metadata.json: {graph_id: {filename, label}}
    - GRAPH_DATA_DIR/graphs/{graph_id}.json: NetworkX node-link format
    """
    
    def __init__(self, graph_dir, metadata_file, split="train", test_size=0.2, 
                 random_state=42, train_ratio=0.8):
        """
        Args:
            graph_dir: Directory containing graph JSON files
            metadata_file: Path to graph_metadata.json
            split: "train" or "test"
            test_size: Proportion for test split
            random_state: For reproducibility
            train_ratio: Ratio of training data in training split
        """
        self.graph_dir = graph_dir
        self.split = split
        self.graphs = []
        self.labels = []
        self.label_encoder = None
        
        # Load metadata
        with open(metadata_file, 'r') as f:
            self.metadata = json.load(f)
        
        # Get all graph IDs and their labels
        graph_ids = list(self.metadata.keys())
        labels = [self.metadata[gid]['label'] for gid in graph_ids]
        
        # Split into train/test (80% train, 20% test)
        train_ids, test_ids = train_test_split(
            graph_ids, test_size=test_size, random_state=random_state,
            stratify=labels
        )
        
        # Encode labels
        self.label_encoder = LabelEncoder()
        self.label_encoder.fit(labels)
        
        # Select split
        selected_ids = train_ids if split == "train" else test_ids
        
        # Load graphs
        print(f"[INFO] Loading {split} graphs ({len(selected_ids)} samples)...")
        for i, graph_id in enumerate(selected_ids):
            graph_path = os.path.join(graph_dir, "graphs", f"{graph_id}.json")
            
            if not os.path.exists(graph_path):
                print(f"[WARNING] Graph file not found: {graph_path}")
                continue
            
            try:
                with open(graph_path, 'r') as f:
                    graph_data = json.load(f)
                
                label = self.metadata[graph_id]['label']
                self.graphs.append(graph_data)
                self.labels.append(self.label_encoder.transform([label])[0])
                
                if (i + 1) % 1000 == 0:
                    print(f"[INFO] Loaded {i + 1}/{len(selected_ids)} graphs")
            
            except Exception as e:
                print(f"[ERROR] Failed to load {graph_path}: {str(e)}")
                continue
        
        print(f"[INFO] Successfully loaded {len(self.graphs)} graphs for {split} split")
    
    def __len__(self):
        return len(self.graphs)
    
    def __getitem__(self, idx):
        """Convert graph JSON to PyTorch Geometric Data object"""
        graph_data = self.graphs[idx]
        label = self.labels[idx]
        
        # Extract nodes and edges from node-link format
        nodes = {n['id']: n for n in graph_data['nodes']}
        
        # Create node feature matrix (one-hot encoding of node types)
        node_types = list(set([n['type'] for n in graph_data['nodes']]))
        type_to_idx = {t: i for i, t in enumerate(node_types)}
        
        num_nodes = len(nodes)
        num_types = len(node_types)
        
        # Node features: one-hot encoding of node type
        x = np.zeros((num_nodes, num_types), dtype=np.float32)
        node_id_to_idx = {}
        
        for i, (node_id, node) in enumerate(sorted(nodes.items())):
            node_id_to_idx[node_id] = i
            node_type = node['type']
            x[i, type_to_idx[node_type]] = 1.0
        
        # Edge list
        edge_list = []
        for edge in graph_data['links']:
            source_idx = node_id_to_idx.get(edge['source'])
            target_idx = node_id_to_idx.get(edge['target'])
            
            if source_idx is not None and target_idx is not None:
                # Add both directions for undirected graph
                edge_list.append([source_idx, target_idx])
                edge_list.append([target_idx, source_idx])
        
        if edge_list:
            edge_index = np.array(edge_list, dtype=np.int64).T
        else:
            # Handle isolated nodes
            edge_index = np.array([[], []], dtype=np.int64)
        
        # Convert to PyTorch tensors
        x = torch.tensor(x, dtype=torch.float32)
        edge_index = torch.tensor(edge_index, dtype=torch.long)
        y = torch.tensor(label, dtype=torch.long)
        
        # Create PyTorch Geometric Data object
        data = Data(x=x, edge_index=edge_index, y=y)
        
        return data
    
    def get_num_classes(self):
        return len(self.label_encoder.classes_)
    
    def get_class_names(self):
        return self.label_encoder.classes_


