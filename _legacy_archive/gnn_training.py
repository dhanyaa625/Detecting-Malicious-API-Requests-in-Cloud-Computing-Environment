# 2. GNN MODELS
# ─────────────────────────────────────────────────────────────────────────────

class GCNModel(nn.Module):
    """Graph Convolutional Network (GCN) for malware classification"""
    
    def __init__(self, input_dim, hidden_dim, output_dim, dropout=0.3):
        super(GCNModel, self).__init__()
        self.conv1 = GCNConv(input_dim, hidden_dim)
        self.conv2 = GCNConv(hidden_dim, hidden_dim)
        self.conv3 = GCNConv(hidden_dim, hidden_dim)
        self.fc = nn.Linear(hidden_dim, output_dim)
        self.dropout = nn.Dropout(dropout)
        self.relu = nn.ReLU()
    
    def forward(self, x, edge_index, batch):
        """
        Args:
            x: Node features [num_nodes, input_dim]
            edge_index: Edge indices [2, num_edges]
            batch: Batch assignment vector [num_nodes]
        """
        # GCN layers with ReLU activation
        x = self.relu(self.conv1(x, edge_index))
        x = self.dropout(x)
        x = self.relu(self.conv2(x, edge_index))
        x = self.dropout(x)
        x = self.relu(self.conv3(x, edge_index))
        
        # Global mean pooling (aggregate node representations per graph)
        x = global_mean_pool(x, batch)
        
        # Classification layer
        x = self.fc(x)
        return x


class GATModel(nn.Module):
    """Graph Attention Network (GAT) for malware classification"""
    
    def __init__(self, input_dim, hidden_dim, output_dim, num_heads=4, dropout=0.3):
        super(GATModel, self).__init__()
        self.conv1 = GATConv(input_dim, hidden_dim, heads=num_heads, dropout=dropout)
        self.conv2 = GATConv(hidden_dim * num_heads, hidden_dim, heads=num_heads, dropout=dropout)
        self.conv3 = GATConv(hidden_dim * num_heads, hidden_dim, heads=1, dropout=dropout)
        self.fc = nn.Linear(hidden_dim, output_dim)
        self.dropout = nn.Dropout(dropout)
        self.relu = nn.ReLU()
    
    def forward(self, x, edge_index, batch):
        """
        Args:
            x: Node features [num_nodes, input_dim]
            edge_index: Edge indices [2, num_edges]
            batch: Batch assignment vector [num_nodes]
        """
        # GAT layers with ReLU activation
        x = self.relu(self.conv1(x, edge_index))
        x = self.dropout(x)
        x = self.relu(self.conv2(x, edge_index))
        x = self.dropout(x)
        x = self.conv3(x, edge_index)
        
        # Global mean pooling
        x = global_mean_pool(x, batch)
        
        # Classification layer
        x = self.fc(x)
        return x


# ─────────────────────────────────────────────────────────────────────────────
# 3. TRAINING FUNCTIONS
# ─────────────────────────────────────────────────────────────────────────────

def train_epoch(model, train_loader, optimizer, criterion, device):
    """Train for one epoch"""
    model.train()
    total_loss = 0
    correct = 0
    total = 0
    
    for batch in train_loader:
        batch = batch.to(device)
        optimizer.zero_grad()
        
        out = model(batch.x, batch.edge_index, batch.batch)
        loss = criterion(out, batch.y)
        loss.backward()
        optimizer.step()
        
        total_loss += loss.item()
        pred = out.argmax(dim=1)
        correct += (pred == batch.y).sum().item()
        total += batch.y.size(0)
    
    avg_loss = total_loss / len(train_loader)
    accuracy = correct / total
    return avg_loss, accuracy


def evaluate(model, test_loader, criterion, device):
    """Evaluate model on test set"""
    model.eval()
    total_loss = 0
    correct = 0
    total = 0
    all_preds = []
    all_labels = []
    all_probs = []
    
    with torch.no_grad():
        for batch in test_loader:
            batch = batch.to(device)
            out = model(batch.x, batch.edge_index, batch.batch)
            loss = criterion(out, batch.y)
            
            total_loss += loss.item()
            pred = out.argmax(dim=1)
            correct += (pred == batch.y).sum().item()
            total += batch.y.size(0)
            
            all_preds.extend(pred.cpu().numpy())
            all_labels.extend(batch.y.cpu().numpy())
            
            # Get probabilities for ROC-AUC
            probs = torch.softmax(out, dim=1)
            all_probs.extend(probs.cpu().numpy())
    
    avg_loss = total_loss / len(test_loader)
    accuracy = correct / total
    
    return avg_loss, accuracy, np.array(all_preds), np.array(all_labels), np.array(all_probs)


# ─────────────────────────────────────────────────────────────────────────────
# 4. MAIN TRAINING PIPELINE
# ─────────────────────────────────────────────────────────────────────────────

def main():
    """Main training pipeline"""
    
    print("[STEP 1] Loading graph dataset...")
    try:
        # Check if graph data exists
        if not os.path.exists(os.path.join(GRAPH_DATA_DIR, "graph_metadata.json")):
            print(f"[ERROR] Graph metadata not found at {GRAPH_DATA_DIR}")
            print("[INFO] Please run Member 3's data_to_graph.py first to generate graphs")
            print(f"[INFO] Expected: {os.path.join(GRAPH_DATA_DIR, 'graph_metadata.json')}")
            return
        
        # Load training and test datasets
        train_dataset = MalwareGraphDataset(
            graph_dir=GRAPH_DATA_DIR,
            metadata_file=os.path.join(GRAPH_DATA_DIR, "graph_metadata.json"),
            split="train"
        )
        
        test_dataset = MalwareGraphDataset(
            graph_dir=GRAPH_DATA_DIR,
            metadata_file=os.path.join(GRAPH_DATA_DIR, "graph_metadata.json"),
            split="test"
        )
        
        num_classes = train_dataset.get_num_classes()
        class_names = train_dataset.get_class_names()
        
        print(f"[INFO] Training samples: {len(train_dataset)}")
        print(f"[INFO] Test samples: {len(test_dataset)}")
        print(f"[INFO] Number of classes: {num_classes}")
        print(f"[INFO] Classes: {class_names}")
        
    except Exception as e:
        print(f"[ERROR] Failed to load dataset: {str(e)}")
        return
    
    print("\n[STEP 2] Creating data loaders...")
    train_loader = GeoDataLoader(train_dataset, batch_size=BATCH_SIZE, shuffle=True)
    test_loader = GeoDataLoader(test_dataset, batch_size=BATCH_SIZE, shuffle=False)
    
    # Get input dimension from first batch
    sample_batch = next(iter(train_loader))
    input_dim = sample_batch.x.shape[1]
    print(f"[INFO] Input feature dimension (node types): {input_dim}")
    
    print(f"\n[STEP 3] Initializing {MODEL_TYPE} model...")
    if MODEL_TYPE == "GCN":
        model = GCNModel(
            input_dim=input_dim,
            hidden_dim=HIDDEN_DIM,
            output_dim=num_classes,
            dropout=DROPOUT
        )
    elif MODEL_TYPE == "GAT":
        model = GATModel(
            input_dim=input_dim,
            hidden_dim=HIDDEN_DIM,
            output_dim=num_classes,
            dropout=DROPOUT
        )
    else:
        raise ValueError(f"Unknown model type: {MODEL_TYPE}")
    
    model = model.to(DEVICE)
    print(f"[INFO] Model parameters: {sum(p.numel() for p in model.parameters()):,}")
    
    # Optimizer and loss function
    optimizer = optim.Adam(model.parameters(), lr=LEARNING_RATE)
    criterion = nn.CrossEntropyLoss()
    
    print(f"\n[STEP 4] Training for {NUM_EPOCHS} epochs...")
    train_losses = []
    train_accs = []
    test_losses = []
    test_accs = []
    
    best_test_acc = 0
    best_model_path = os.path.join(OUTPUT_DIR, "best_model.pt")
    
    for epoch in range(NUM_EPOCHS):
        train_loss, train_acc = train_epoch(model, train_loader, optimizer, criterion, DEVICE)
        test_loss, test_acc, _, _, _ = evaluate(model, test_loader, criterion, DEVICE)
        
        train_losses.append(train_loss)
        train_accs.append(train_acc)
        test_losses.append(test_loss)
        test_accs.append(test_acc)
        
        # Save best model
        if test_acc > best_test_acc:
            best_test_acc = test_acc
            torch.save(model.state_dict(), best_model_path)
        
        if (epoch + 1) % 10 == 0:
            print(f"Epoch {epoch+1:03d} | "
                  f"Train Loss: {train_loss:.4f}, Train Acc: {train_acc:.4f} | "
                  f"Test Loss: {test_loss:.4f}, Test Acc: {test_acc:.4f}")
    
    print(f"\n[STEP 5] Loading best model and evaluating...")
    model.load_state_dict(torch.load(best_model_path))
    test_loss, test_acc, preds, labels, probs = evaluate(model, test_loader, criterion, DEVICE)
    
    print(f"[INFO] Final Test Accuracy: {test_acc:.4f}")
    print(f"[INFO] Final Test Loss: {test_loss:.4f}")
    
    # Calculate metrics
    precision = precision_score(labels, preds, average='macro', zero_division=0)
    recall = recall_score(labels, preds, average='macro', zero_division=0)
    f1 = f1_score(labels, preds, average='macro', zero_division=0)
    
    print(f"[INFO] Precision (macro): {precision:.4f}")
    print(f"[INFO] Recall (macro): {recall:.4f}")
    print(f"[INFO] F1-Score (macro): {f1:.4f}")
    
    print(f"\n[STEP 6] Saving results and artifacts...")
    
    # Save model
    model_path = os.path.join(OUTPUT_DIR, "model_final.pt")
    torch.save(model.state_dict(), model_path)
    print(f"[INFO] Model saved to {model_path}")
    
    # Save training history
    history = {
        'train_loss': train_losses,
        'train_acc': train_accs,
        'test_loss': test_losses,
        'test_acc': test_accs
    }
    history_path = os.path.join(OUTPUT_DIR, "training_history.json")
    with open(history_path, 'w') as f:
        json.dump(history, f)
    print(f"[INFO] Training history saved to {history_path}")
    
    # Save predictions in Member 1 compatible format (Prospect/Aspect/Context)
    predictions_json = {
        'model_type': MODEL_TYPE,
        'accuracy': float(test_acc),
        'precision': float(precision),
        'recall': float(recall),
        'f1_score': float(f1),
        'num_test_samples': len(labels),
        'class_names': list(class_names),
        'predictions': []
    }
    
    for i in range(len(labels)):
        pred_entry = {
            'true_label': str(class_names[labels[i]]),
            'predicted_label': str(class_names[preds[i]]),
            'confidence': float(probs[i, preds[i]]),
            'all_class_probabilities': {
                class_names[j]: float(probs[i, j])
                for j in range(num_classes)
            },
            'prospect': {
                'predicted_malware_type': str(class_names[preds[i]]),
                'confidence_score': float(probs[i, preds[i]])
            },
            'aspect': {
                'feature_vector': 'See node embeddings in advanced output',
                'graph_structure_features': 'Available in detailed analysis'
            },
            'context': {
                'true_label': str(class_names[labels[i]]),
                'prediction_correct': bool(preds[i] == labels[i]),
                'evaluation_set': 'test'
            }
        }
        predictions_json['predictions'].append(pred_entry)
    
    predictions_path = os.path.join(OUTPUT_DIR, "gnn_predictions.json")
    with open(predictions_path, 'w') as f:
        json.dump(predictions_json, f, indent=2)
    print(f"[INFO] Predictions saved to {predictions_path}")
    
    # Plot training history
    plt.figure(figsize=(12, 5))
    
    plt.subplot(1, 2, 1)
    plt.plot(train_losses, label='Train Loss')
    plt.plot(test_losses, label='Test Loss')
    plt.xlabel('Epoch')
    plt.ylabel('Loss')
    plt.title('Training History - Loss')
    plt.legend()
    plt.grid(True)
    
    plt.subplot(1, 2, 2)
    plt.plot(train_accs, label='Train Accuracy')
    plt.plot(test_accs, label='Test Accuracy')
    plt.xlabel('Epoch')
    plt.ylabel('Accuracy')
    plt.title('Training History - Accuracy')
    plt.legend()
    plt.grid(True)
    
    history_plot_path = os.path.join(OUTPUT_DIR, "training_history.png")
    plt.savefig(history_plot_path, dpi=300, bbox_inches='tight')
    plt.close()
    print(f"[INFO] Training history plot saved to {history_plot_path}")
    
    # Plot confusion matrix
    cm = confusion_matrix(labels, preds)
    plt.figure(figsize=(10, 8))
    sns.heatmap(cm, annot=True, fmt='d', xticklabels=class_names, yticklabels=class_names)
    plt.xlabel('Predicted Label')
    plt.ylabel('True Label')
    plt.title('Confusion Matrix')
    cm_plot_path = os.path.join(OUTPUT_DIR, "confusion_matrix.png")
    plt.savefig(cm_plot_path, dpi=300, bbox_inches='tight')
    plt.close()
    print(f"[INFO] Confusion matrix plot saved to {cm_plot_path}")
    
    # Save summary
    summary = {
        'model_type': MODEL_TYPE,
        'config': {
            'batch_size': BATCH_SIZE,
            'num_epochs': NUM_EPOCHS,
            'learning_rate': LEARNING_RATE,
            'hidden_dim': HIDDEN_DIM,
            'dropout': DROPOUT
        },
        'results': {
            'test_accuracy': float(test_acc),
            'test_loss': float(test_loss),
            'precision': float(precision),
            'recall': float(recall),
            'f1_score': float(f1),
            'num_test_samples': len(labels),
            'num_classes': num_classes
        }
    }
    
    summary_path = os.path.join(OUTPUT_DIR, "summary.json")
    with open(summary_path, 'w') as f:
        json.dump(summary, f, indent=2)
    print(f"[INFO] Summary saved to {summary_path}")
    
    print(f"\n[COMPLETE] Training finished!")
    print(f"[INFO] All outputs saved to {OUTPUT_DIR}")
    print(f"[INFO] Use gnn_predictions.json output for Member 1's agent orchestration")


if __name__ == "__main__":
    main()
